//! `Introspector::load` against a real PostgreSQL server (the container of
//! `docker-compose.yml`, see docs/testing-databases.md):
//!
//! ```bash
//! docker compose up -d postgres
//! cargo test -p db-postgres --test it load:: -- --ignored
//! ```
//!
//! Each test works in a schema of its own (`pxpg_load_<test>`), created and
//! dropped by the test.

use std::time::Instant;

use db_core::schema::{
    ArgumentMode, ConstraintKind, IdentityKind, Level, ObjectDetail, ObjectKind, Scope,
    TypeCategory, introspector,
};
use db_core::{ConnectParams, Connection, Driver, ExecOptions, Secret};
use db_postgres::PostgresDriver;
use db_testkit::{assert_load_matches_per_object, load_statements};

fn env_or(name: &str, default: &str) -> String {
    std::env::var(name).unwrap_or_else(|_| default.to_owned())
}

async fn connect() -> Box<dyn Connection> {
    let params = ConnectParams {
        host: env_or("PYOXIDE_TEST_PG_HOST", "localhost"),
        port: env_or("PYOXIDE_TEST_PG_PORT", "55432")
            .parse()
            .expect("port"),
        database: "pyoxide".into(),
        user: "pyoxide".into(),
        password: Secret::new(env_or("PYOXIDE_DB_PASSWORD", "pyoxide")),
        ..ConnectParams::default()
    };
    PostgresDriver
        .connect(&params)
        .await
        .expect("connect to the test PostgreSQL (docker compose up -d postgres)")
}

async fn exec(conn: &dyn Connection, sql: &str) {
    if let Err(e) = conn.execute(sql, &[], &ExecOptions::default()).await {
        panic!("{sql}: {e}");
    }
}

async fn fresh_schema(conn: &dyn Connection, schema: &str) {
    drop_schema(conn, schema).await;
    exec(conn, &format!("CREATE SCHEMA {schema}")).await;
}

/// Drops the tables in blocks of 200 first: dropping thousands of tables in
/// one transaction needs more locks than the server has by default.
async fn drop_schema(conn: &dyn Connection, schema: &str) {
    loop {
        let rs = conn
            .query(
                "SELECT count(*) FROM pg_catalog.pg_tables WHERE schemaname = $1",
                &[schema.into()],
                1,
            )
            .await
            .unwrap();
        if rs.rows[0][0].as_i64() == Some(0) {
            break;
        }
        exec(
            conn,
            &format!(
                "DO $$ DECLARE t text; BEGIN \
                   FOR t IN SELECT tablename FROM pg_catalog.pg_tables \
                            WHERE schemaname = '{schema}' \
                            ORDER BY tablename DESC LIMIT 200 LOOP \
                     EXECUTE format('DROP TABLE {schema}.%I CASCADE', t); \
                   END LOOP; \
                 END $$"
            ),
        )
        .await;
    }
    exec(conn, &format!("DROP SCHEMA IF EXISTS {schema} CASCADE")).await;
}

async fn details_fixture(conn: &dyn Connection, schema: &str) {
    fresh_schema(conn, schema).await;
    exec(conn, &format!("COMMENT ON SCHEMA {schema} IS 'load test'")).await;
    exec(conn, &format!("SET search_path = {schema}")).await;
    for sql in [
        "CREATE TYPE mood AS ENUM ('sad', 'ok', 'happy')",
        "CREATE TYPE pair AS (a integer, b text)",
        "CREATE DOMAIN posint AS integer NOT NULL DEFAULT 1 CHECK (VALUE > 0)",
        "CREATE TYPE span AS RANGE (subtype = integer)",
        "CREATE SEQUENCE seq_all START 7 INCREMENT 3 MINVALUE 5 MAXVALUE 900 CACHE 20 CYCLE",
        "CREATE TABLE parent (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            code text NOT NULL,
            note text,
            UNIQUE (code))",
        "COMMENT ON TABLE parent IS 'parent rows'",
        "COMMENT ON COLUMN parent.code IS 'the code'",
        "CREATE TABLE child (
            id integer PRIMARY KEY,
            parent_id integer CONSTRAINT child_parent_fk REFERENCES parent (id)
                ON DELETE CASCADE ON UPDATE SET NULL DEFERRABLE INITIALLY DEFERRED,
            other_id integer,
            qty integer DEFAULT 1 CONSTRAINT qty_positive CHECK (qty > 0),
            label text,
            double_qty integer GENERATED ALWAYS AS (qty * 2) STORED,
            mood mood)",
        "ALTER TABLE child ADD CONSTRAINT other_fk FOREIGN KEY (other_id)
            REFERENCES parent (id) NOT VALID",
        "CREATE INDEX child_lbl ON child (lower(label), qty) INCLUDE (parent_id) WHERE qty > 1",
        "CREATE INDEX child_gin ON child USING hash (label)",
        "CREATE VIEW v AS SELECT id, label FROM child",
        "CREATE MATERIALIZED VIEW mv AS SELECT count(*) AS n FROM child WITH NO DATA",
        "CREATE UNLOGGED TABLE scratch (x integer)",
        "CREATE TABLE part (d date NOT NULL) PARTITION BY LIST (d)",
        "CREATE TABLE part_a PARTITION OF part FOR VALUES IN ('2026-01-01')",
        "CREATE TABLE part_rest PARTITION OF part DEFAULT",
        "CREATE FUNCTION add(a integer, b integer DEFAULT 1) RETURNS integer
            LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE AS 'SELECT a + b'",
        "CREATE FUNCTION add(a text, VARIADIC more integer[]) RETURNS text
            LANGUAGE sql SECURITY DEFINER AS $$ SELECT a $$",
        "CREATE FUNCTION pairs(OUT x integer, OUT y text) RETURNS record
            LANGUAGE sql AS 'SELECT 1, ''a'''",
        "CREATE FUNCTION rows_of(n integer) RETURNS TABLE (i integer, t text)
            LANGUAGE sql AS 'SELECT g, g::text FROM generate_series(1, n) g'",
        "CREATE PROCEDURE bump(INOUT counter integer, step integer DEFAULT 1)
            LANGUAGE plpgsql AS 'BEGIN counter := counter + step; END'",
        "CREATE FUNCTION tf() RETURNS trigger LANGUAGE plpgsql AS 'BEGIN RETURN NEW; END'",
        "CREATE TRIGGER child_trg BEFORE INSERT OR UPDATE ON child
            FOR EACH ROW WHEN (NEW.qty > 0) EXECUTE FUNCTION tf()",
        "CREATE TRIGGER child_upd AFTER UPDATE ON child
            FOR EACH ROW WHEN (OLD.qty IS DISTINCT FROM NEW.qty) EXECUTE FUNCTION tf()",
        "CREATE TRIGGER child_stmt AFTER DELETE OR TRUNCATE ON child
            FOR EACH STATEMENT EXECUTE FUNCTION tf()",
        "ALTER TABLE child DISABLE TRIGGER child_stmt",
    ] {
        exec(conn, sql).await;
    }
    exec(conn, "RESET search_path").await;
}

#[tokio::test]
#[ignore = "needs the postgres container"]
async fn bulk_load_equals_the_per_object_reads_on_a_rich_schema() {
    const SCHEMA: &str = "pxpg_load_equal";
    let conn = connect().await;
    details_fixture(&*conn, SCHEMA).await;
    for level in [Level::Names, Level::Structure, Level::Full] {
        assert_load_matches_per_object(&*conn, &Scope::list([SCHEMA]), level, &|_| true).await;
    }
    exec(&*conn, &format!("DROP SCHEMA {SCHEMA} CASCADE")).await;
}

#[tokio::test]
#[ignore = "needs the postgres container"]
async fn details_of_every_kind() {
    const SCHEMA: &str = "pxpg_load_details";
    let conn = connect().await;
    details_fixture(&*conn, SCHEMA).await;
    let intro = introspector(&*conn);
    let snapshot = intro
        .load(&Scope::list([SCHEMA]), Level::Full)
        .await
        .unwrap();
    let s = snapshot.schema(SCHEMA).unwrap();
    assert_eq!(s.info.comment.as_deref(), Some("load test"));
    assert_eq!(s.info.owner.as_deref(), Some("pyoxide"));

    let object = |kind: ObjectKind, name: &str| {
        s.objects
            .iter()
            .find(|o| o.kind == kind && o.name == name)
            .unwrap_or_else(|| panic!("{kind:?} {name}"))
    };
    let table = |name: &str| match object(ObjectKind::Table, name).detail.clone() {
        Some(ObjectDetail::Table(t)) => t,
        other => panic!("{name}: {other:?}"),
    };

    // Owner and comment of an object.
    let parent = object(ObjectKind::Table, "parent");
    assert_eq!(parent.owner.as_deref(), Some("pyoxide"));
    assert_eq!(parent.comment.as_deref(), Some("parent rows"));

    // Partitions with their parent and bounds.
    let part = table("part");
    assert!(part.partitioned);
    assert_eq!(part.partition_key.as_deref(), Some("LIST (d)"));
    assert!(part.partition_of.is_none());
    let a = table("part_a").partition_of.expect("a partition");
    assert_eq!((a.schema.as_str(), a.table.as_str()), (SCHEMA, "part"));
    assert_eq!(a.bounds.as_deref(), Some("FOR VALUES IN ('2026-01-01')"));
    assert_eq!(
        table("part_rest").partition_of.unwrap().bounds.as_deref(),
        Some("DEFAULT")
    );
    assert!(table("scratch").unlogged && !table("scratch").partitioned);

    // Materialized view with no data.
    let ObjectDetail::View(mv) = object(ObjectKind::MaterializedView, "mv")
        .detail
        .clone()
        .unwrap()
    else {
        panic!("a view detail");
    };
    assert_eq!(mv.populated, Some(false));

    // Sequence parameters.
    let ObjectDetail::Sequence(seq) = object(ObjectKind::Sequence, "seq_all")
        .detail
        .clone()
        .unwrap()
    else {
        panic!("a sequence detail");
    };
    assert_eq!(seq.data_type.as_deref(), Some("bigint"));
    assert_eq!(
        (
            seq.start.as_deref(),
            seq.min.as_deref(),
            seq.max.as_deref(),
            seq.increment.as_deref()
        ),
        (Some("7"), Some("5"), Some("900"), Some("3"))
    );
    assert!(seq.cycle);
    assert_eq!(seq.cache, Some(20));

    // Routines: overloads, modes, defaults.
    let routines: Vec<_> = s
        .objects
        .iter()
        .filter(|o| o.name == "add" && o.kind == ObjectKind::Function)
        .collect();
    assert_eq!(routines.len(), 2, "two overloads");
    let details: Vec<_> = routines
        .iter()
        .map(|o| match o.detail.clone() {
            Some(ObjectDetail::Routine(r)) => r,
            other => panic!("{other:?}"),
        })
        .collect();
    let ints = details
        .iter()
        .find(|r| r.signature == "a integer, b integer")
        .unwrap();
    assert_eq!(ints.return_type.as_deref(), Some("integer"));
    assert_eq!(ints.language.as_deref(), Some("sql"));
    assert_eq!(
        ints.characteristics,
        ["IMMUTABLE", "STRICT", "PARALLEL SAFE"]
    );
    assert_eq!(ints.arguments.len(), 2);
    assert_eq!(ints.arguments[0].name.as_deref(), Some("a"));
    assert!(!ints.arguments[0].has_default && ints.arguments[1].has_default);
    let texts = details
        .iter()
        .find(|r| r.signature.starts_with("a text"))
        .unwrap();
    assert_eq!(texts.arguments[1].mode, ArgumentMode::Variadic);
    assert_eq!(texts.arguments[1].data_type, "integer[]");
    assert_eq!(texts.characteristics, ["SECURITY DEFINER"]);

    let routine = |name: &str| match object(
        if name == "bump" {
            ObjectKind::Procedure
        } else {
            ObjectKind::Function
        },
        name,
    )
    .detail
    .clone()
    {
        Some(ObjectDetail::Routine(r)) => r,
        other => panic!("{name}: {other:?}"),
    };
    let pairs = routine("pairs");
    assert_eq!(
        pairs
            .arguments
            .iter()
            .map(|a| (a.name.clone().unwrap(), a.mode, a.data_type.clone()))
            .collect::<Vec<_>>(),
        [
            ("x".into(), ArgumentMode::Out, "integer".into()),
            ("y".into(), ArgumentMode::Out, "text".into())
        ]
    );
    let rows_of = routine("rows_of");
    assert_eq!(
        rows_of.return_type.as_deref(),
        Some("TABLE(i integer, t text)")
    );
    assert_eq!(
        rows_of.arguments.iter().map(|a| a.mode).collect::<Vec<_>>(),
        [ArgumentMode::In, ArgumentMode::Table, ArgumentMode::Table]
    );
    let bump = routine("bump");
    assert_eq!(bump.return_type, None, "a procedure returns nothing");
    assert_eq!(bump.arguments[0].mode, ArgumentMode::InOut);
    assert!(!bump.arguments[0].has_default && bump.arguments[1].has_default);

    // Triggers.
    let trigger = |name: &str| match object(ObjectKind::Trigger, name).detail.clone() {
        Some(ObjectDetail::Trigger(t)) => t,
        other => panic!("{name}: {other:?}"),
    };
    let row = trigger("child_trg");
    assert_eq!(row.events, ["INSERT", "UPDATE"]);
    assert_eq!(row.timing.as_deref(), Some("BEFORE"));
    assert!(row.each_row && !row.disabled);
    assert_eq!(row.function.as_deref(), Some("pxpg_load_details.tf"));
    assert_eq!(row.condition.as_deref(), Some("new.qty > 0"));
    assert_eq!(
        trigger("child_upd").condition.as_deref(),
        Some("old.qty IS DISTINCT FROM new.qty"),
        "a condition that reads OLD and NEW"
    );
    assert_eq!(
        object(ObjectKind::Trigger, "child_trg").parent.as_deref(),
        Some("child")
    );
    let stmt = trigger("child_stmt");
    assert_eq!(stmt.events, ["DELETE", "TRUNCATE"]);
    assert_eq!(stmt.timing.as_deref(), Some("AFTER"));
    assert!(!stmt.each_row && stmt.disabled);
    assert_eq!(stmt.condition, None);

    // Types.
    let ty = |name: &str| match object(ObjectKind::Type, name).detail.clone() {
        Some(ObjectDetail::Type(t)) => t,
        other => panic!("{name}: {other:?}"),
    };
    let mood = ty("mood");
    assert_eq!(mood.category, TypeCategory::Enum);
    assert_eq!(mood.labels, ["sad", "ok", "happy"]);
    let pair = ty("pair");
    assert_eq!(pair.category, TypeCategory::Composite);
    assert_eq!(
        pair.attributes
            .iter()
            .map(|a| (a.name.as_str(), a.data_type.as_str()))
            .collect::<Vec<_>>(),
        [("a", "integer"), ("b", "text")]
    );
    let posint = ty("posint");
    assert_eq!(posint.category, TypeCategory::Domain);
    assert_eq!(posint.base_type.as_deref(), Some("integer"));
    assert!(posint.not_null);
    assert_eq!(posint.default.as_deref(), Some("1"));
    assert_eq!(posint.constraints, ["CHECK (VALUE > 0)"]);
    let span = ty("span");
    assert_eq!(span.category, TypeCategory::Range);
    assert_eq!(span.base_type.as_deref(), Some("integer"));

    // Columns: identity, generated, comments.
    let child = s.relation("child").unwrap();
    let col = |name: &str| child.columns.iter().find(|c| c.name == name).unwrap();
    let generated = col("double_qty").generated.clone().unwrap();
    assert!(generated.stored);
    assert_eq!(generated.expression.as_deref(), Some("(qty * 2)"));
    assert!(col("qty").generated.is_none());
    let parent_rel = s.relation("parent").unwrap();
    let id = &parent_rel.columns[0];
    assert_eq!(id.identity, Some(IdentityKind::ByDefault));
    assert!(id.auto_increment);
    assert_eq!(parent_rel.columns[1].comment.as_deref(), Some("the code"));
    assert_eq!(col("mood").data_type, format!("{SCHEMA}.mood"));

    // Indexes: expression, include, partial.
    let lbl = child
        .indexes
        .iter()
        .find(|i| i.name == "child_lbl")
        .unwrap();
    assert_eq!(lbl.columns, ["lower(label)", "qty"]);
    assert_eq!(lbl.expressions, [0]);
    assert_eq!(lbl.include, ["parent_id"]);
    assert_eq!(lbl.predicate.as_deref(), Some("qty > 1"));
    let hash = child
        .indexes
        .iter()
        .find(|i| i.name == "child_gin")
        .unwrap();
    assert_eq!(hash.method.as_deref(), Some("hash"));
    assert!(hash.predicate.is_none() && hash.expressions.is_empty());

    // Foreign keys: actions, deferral, validation.
    let fk = child
        .constraints
        .iter()
        .find(|c| c.name == "child_parent_fk")
        .unwrap();
    assert_eq!(fk.kind, ConstraintKind::ForeignKey);
    assert_eq!(fk.on_delete.as_deref(), Some("CASCADE"));
    assert_eq!(fk.on_update.as_deref(), Some("SET NULL"));
    assert_eq!(fk.match_type.as_deref(), Some("SIMPLE"));
    assert!(fk.deferrable && fk.initially_deferred && !fk.not_validated);
    let other = child
        .constraints
        .iter()
        .find(|c| c.name == "other_fk")
        .unwrap();
    assert!(other.not_validated && !other.deferrable);
    assert_eq!(other.on_update.as_deref(), Some("NO ACTION"));
    let check = child
        .constraints
        .iter()
        .find(|c| c.name == "qty_positive")
        .unwrap();
    assert_eq!(check.check.as_deref(), Some("qty > 0"));
    assert!(check.on_update.is_none() && check.match_type.is_none());

    // Source text equals the lazy read; overloads each have their own text.
    let source = |kind: ObjectKind, name: &str| {
        s.sources
            .iter()
            .filter(|x| x.kind == kind && x.name == name)
            .map(|x| x.text.clone())
            .collect::<Vec<_>>()
    };
    for (kind, name) in [
        (ObjectKind::View, "v"),
        (ObjectKind::MaterializedView, "mv"),
        (ObjectKind::Procedure, "bump"),
        (ObjectKind::Trigger, "child_trg"),
    ] {
        assert_eq!(
            source(kind, name),
            [intro.source(SCHEMA, name, kind).await.unwrap().unwrap()],
            "{name}"
        );
    }
    let adds = source(ObjectKind::Function, "add");
    assert_eq!(adds.len(), 2);
    assert!(
        adds.iter()
            .all(|t| t.starts_with("CREATE OR REPLACE FUNCTION"))
    );
    assert!(source(ObjectKind::Table, "parent").is_empty());

    exec(&*conn, &format!("DROP SCHEMA {SCHEMA} CASCADE")).await;
}

#[tokio::test]
#[ignore = "needs the postgres container"]
async fn scopes_pick_schemas() {
    let conn = connect().await;
    for schema in ["pxpg_load_scope_a", "pxpg_load_scope_b"] {
        fresh_schema(&*conn, schema).await;
        exec(&*conn, &format!("CREATE TABLE {schema}.t (a integer)")).await;
    }
    let intro = introspector(&*conn);
    let names = |scope: Scope| {
        let intro = &intro;
        async move {
            intro
                .load(&scope, Level::Names)
                .await
                .unwrap()
                .schemas
                .into_iter()
                .map(|s| s.info.name)
                .collect::<Vec<_>>()
        }
    };
    assert_eq!(names(Scope::current()).await, ["public"]);
    assert_eq!(
        names(Scope::list([
            "pxpg_load_scope_b",
            "pxpg_load_scope_a",
            "nope"
        ]))
        .await,
        ["pxpg_load_scope_a", "pxpg_load_scope_b"],
        "schemas come in name order, unknown names are skipped"
    );
    assert_eq!(
        names(Scope::patterns(["PXPG_LOAD_SCOPE_*"])).await,
        ["pxpg_load_scope_a", "pxpg_load_scope_b"]
    );
    let all = names(Scope::all()).await;
    assert!(all.contains(&"public".to_owned()) && all.contains(&"pxpg_load_scope_a".to_owned()));
    assert!(
        !all.iter()
            .any(|n| n == "pg_catalog" || n == "information_schema")
    );
    let with_system = names(Scope::all().with_system(true)).await;
    assert!(with_system.contains(&"pg_catalog".to_owned()));
    assert!(with_system.contains(&"information_schema".to_owned()));
    assert_eq!(
        names(Scope::list(["pg_catalog"])).await,
        ["pg_catalog"],
        "a listed system schema is read"
    );

    // The system catalog loads too (a few thousand columns), at every level.
    for level in [Level::Names, Level::Structure, Level::Full] {
        let snapshot = intro
            .load(&Scope::list(["pg_catalog"]), level)
            .await
            .unwrap();
        assert!(snapshot.schemas[0].objects.len() > 100);
    }
    for schema in ["pxpg_load_scope_a", "pxpg_load_scope_b"] {
        exec(&*conn, &format!("DROP SCHEMA {schema} CASCADE")).await;
    }
}

const BIG: &str = "pxpg_load_big";

/// `tables` tables with a primary key, a unique key, a foreign key, a check
/// and an index each. Created in blocks of 200 so that no transaction holds
/// more locks than the server allows.
async fn big_schema(conn: &dyn Connection, tables: usize) {
    fresh_schema(conn, BIG).await;
    exec(
        conn,
        &format!(
            "CREATE TABLE {BIG}.t0000 (id integer PRIMARY KEY, code text NOT NULL UNIQUE, \
             created timestamptz DEFAULT now(), qty integer CHECK (qty >= 0))"
        ),
    )
    .await;
    let mut from = 1;
    while from < tables {
        let to = (from + 200).min(tables);
        exec(
            conn,
            &format!(
                "DO $$ BEGIN \
                   FOR i IN {from}..{} LOOP \
                     EXECUTE format('CREATE TABLE {BIG}.t%s (id integer PRIMARY KEY, \
                        parent_id integer REFERENCES {BIG}.t0000 (id), \
                        code text NOT NULL UNIQUE, created timestamptz DEFAULT now(), \
                        qty integer CHECK (qty >= 0))', lpad(i::text, 4, '0')); \
                     EXECUTE format('CREATE INDEX t%s_created ON {BIG}.t%s (created)', \
                        lpad(i::text, 4, '0'), lpad(i::text, 4, '0')); \
                   END LOOP; \
                 END $$",
                to - 1
            ),
        )
        .await;
        from = to;
    }
}

#[tokio::test]
#[ignore = "needs the postgres container"]
async fn statements_do_not_depend_on_the_tables() {
    let conn = connect().await;
    let scope = Scope::list([BIG]);
    big_schema(&*conn, 3).await;
    let mut few = Vec::new();
    for level in [Level::Names, Level::Structure, Level::Full] {
        few.push(load_statements(&*conn, &scope, level).await);
    }
    big_schema(&*conn, 400).await;
    let mut many = Vec::new();
    for level in [Level::Names, Level::Structure, Level::Full] {
        many.push(load_statements(&*conn, &scope, level).await);
    }
    assert_eq!(few, many);
    assert_eq!(many, [5, 8, 11], "schema list, then the queries per family");
    drop_schema(&*conn, BIG).await;
}

/// `cargo test -p db-postgres --release --test it load::bench -- --ignored --nocapture`
#[tokio::test]
#[ignore = "measurement, needs the postgres container, run on demand"]
async fn bench_load_5000_tables() {
    let conn = connect().await;
    big_schema(&*conn, 5000).await;
    exec(&*conn, "ANALYZE").await;
    let intro = introspector(&*conn);
    let scope = Scope::list([BIG]);
    for level in [Level::Names, Level::Structure, Level::Full] {
        let mut times = Vec::new();
        for _ in 0..5 {
            let started = Instant::now();
            let snapshot = intro.load(&scope, level).await.unwrap();
            times.push(started.elapsed());
            let s = snapshot.schema(BIG).unwrap();
            assert_eq!(
                s.objects
                    .iter()
                    .filter(|o| o.kind == ObjectKind::Table)
                    .count(),
                5000
            );
        }
        times.sort();
        println!(
            "postgres load {level:?}: 5000 tables, 25000 columns: median {:.0} ms, best {:.0} ms",
            times[2].as_secs_f64() * 1000.0,
            times[0].as_secs_f64() * 1000.0
        );
    }
    drop_schema(&*conn, BIG).await;
}
